"""Deterministic tests for outer-workflow <-> orchestrator state sync and
request de-duplication.

Run from the repository root:

    python -m check.test_agent_state_sync

No LLM is involved.  The request queue is keyed by a fingerprint of the
request payload, so the same request generated by a later router pass must not
be dispatched again.  These tests pin that contract together with the
field-level step delta used on the way back from the orchestrator.
"""
from __future__ import annotations

import asyncio
import tempfile

from langchain.messages import HumanMessage
from langgraph.types import Send

from catagent.agent import _steps_delta
from catagent.workflow.models import (
    Step,
    dict_reducer,
    orchestrator_request_reducer,
)
from catagent.workflow.router import (
    orchestrator_request_queue,
    request_fingerprint,
    router,
)


def check(condition: bool, message: str) -> None:
    if not condition:
        raise AssertionError(message)


def make_step(step_id: str, **overrides) -> Step:
    values = dict(step_id=step_id, status="pending",
                  preparation_done=True, workdir="")
    values.update(overrides)
    return Step(**values)


def apply_steps(state: dict, update: dict) -> dict:
    state["steps"] = dict_reducer(state.get("steps") or {}, update)
    return state


def apply_requests(state: dict, update: dict) -> dict:
    state["orchestrator_requests"] = orchestrator_request_reducer(
        state.get("orchestrator_requests") or {}, update
    )
    return state


def config(thread_id: str = "t") -> dict:
    return {"configurable": {"thread_id": thread_id}}


# ---------------------------------------------------------------------------
# Step delta: the orchestrator must only return what it changed.
# ---------------------------------------------------------------------------
def test_delta_is_empty_when_nothing_changed() -> None:
    a = make_step("plan-0:step-0:a", status="running", workdir="/w")
    baseline = {a.step_id: a.model_copy(deep=True)}
    current = {a.step_id: a.model_copy(deep=True)}
    check(_steps_delta(baseline, current) == {},
          f"unchanged steps produced a delta: {_steps_delta(baseline, current)}")


def test_delta_contains_only_changed_fields() -> None:
    old = make_step("plan-0:step-0:a", workdir="/w", preparation_done=False)
    new = old.model_copy(deep=True)
    new.preparation_done = True
    delta = _steps_delta({old.step_id: old}, {new.step_id: new})
    check(delta == {old.step_id: {"preparation_done": True}},
          f"unexpected delta: {delta}")


def test_delta_does_not_clobber_concurrent_outer_changes() -> None:
    # The orchestrator still saw preparation_done=False; meanwhile the router
    # has already advanced the outer step to done.  The delta must not contain
    # the stale field, so applying it leaves the outer change intact.
    baseline = make_step("plan-0:step-0:a", preparation_done=False, workdir="/w")
    current = baseline.model_copy(deep=True)
    current.content = "prepared instructions"
    delta = _steps_delta({baseline.step_id: baseline},
                         {current.step_id: current})
    check("preparation_done" not in delta[baseline.step_id],
          f"stale preparation flag was returned: {delta}")

    outer = baseline.model_copy(deep=True)
    outer.preparation_done = True  # router advanced while the agent ran
    merged = dict_reducer({outer.step_id: outer}, delta)
    check(merged[outer.step_id].preparation_done is True,
          "delta reverted a concurrent preparation transition")
    check(merged[outer.step_id].content == "prepared instructions",
          "delta lost the orchestrator change")


def test_delta_keeps_new_steps_as_objects() -> None:
    new = make_step("plan-0:step-9:new", content="do it")
    delta = _steps_delta({}, {new.step_id: new})
    check(isinstance(delta[new.step_id], Step),
          f"new step became a {type(delta[new.step_id])}")
    merged = dict_reducer({}, delta)
    check(isinstance(merged[new.step_id], Step),
          "new step was stored as a plain dict")


# ---------------------------------------------------------------------------
# Request fingerprints and de-duplication.
# ---------------------------------------------------------------------------
def test_fingerprint_ignores_message_ids() -> None:
    first = HumanMessage(content="same request", id="a")
    second = HumanMessage(content="same request", id="b")
    payload_a = {"phase": "logging", "messages": [first]}
    payload_b = {"phase": "logging", "messages": [second]}
    check(request_fingerprint(payload_a) == request_fingerprint(payload_b),
          "message ids changed the request fingerprint")
    payload_c = {"phase": "logging", "messages": [HumanMessage(content="other")]}
    check(request_fingerprint(payload_a) != request_fingerprint(payload_c),
          "different messages produced the same fingerprint")


def preparation_state(step: Step) -> dict:
    return {
        "finalization": False,
        "steps": {step.step_id: step},
        "step_results": {},
        "orchestrator_requests": {},
        "loaded_skills": {},
        "project_workdir": "/tmp",
    }


async def preparation_request(state: dict) -> tuple[str, dict]:
    command = await router(state, config("t-prep"))
    requests = command.update.get("orchestrator_requests") or {}
    check(len(requests) == 1, f"expected one preparation request, got {requests!r}")
    key = next(iter(requests))
    check(requests[key]["payload"].get("phase") == "preparation",
          f"unexpected request: {requests[key]['payload']!r}")
    return key, requests


async def test_identical_request_keeps_one_entry_and_stays_sent() -> None:
    step = make_step("plan-0:step-0:a", preparation_done=False)
    state = preparation_state(step)

    key, requests = await preparation_request(state)
    apply_requests(state, requests)

    # The queue dispatches it and marks the entry sent.
    apply_requests(state, {key: {"sent": True}})
    check(state["orchestrator_requests"][key]["sent"] is True,
          "the queue did not mark the request sent")

    # A later router pass regenerates exactly the same preparation request.
    command = await router(state, config("t-prep"))
    regenerated = command.update.get("orchestrator_requests") or {}
    check(list(regenerated) == [key],
          f"the same request got a new fingerprint: {list(regenerated)!r}")

    apply_requests(state, regenerated)
    check(len(state["orchestrator_requests"]) == 1,
          "the request was duplicated in the queue")
    check(state["orchestrator_requests"][key]["sent"] is True,
          "regenerating the request reset its `sent` flag")


async def test_queue_does_not_redispatch_a_sent_request() -> None:
    step = make_step("plan-0:step-0:a", preparation_done=False)
    state = preparation_state(step)
    key, requests = await preparation_request(state)
    apply_requests(state, requests)

    first = await orchestrator_request_queue(state, config("t-queue"))
    check(isinstance(first.goto, Send) and first.goto.node == "orchestrator_node",
          f"the unsent request was not dispatched: {first.goto!r}")
    apply_requests(state, first.update.get("orchestrator_requests") or {})

    second = await orchestrator_request_queue(state, config("t-queue"))
    check(second.goto == "__end__" or getattr(second.goto, "node", None) == "__end__",
          f"a sent request was dispatched again: {second.goto!r}")


async def test_queue_dispatch_uses_current_step_snapshot() -> None:
    current = make_step("plan-0:step-0:a", preparation_done=True,
                        workdir="/prepared")
    stale = make_step("plan-0:step-0:a", preparation_done=False, workdir="")
    payload = {"phase": "preparation", "messages": [], "steps": {current.step_id: stale}}
    state = {
        "finalization": False,
        "steps": {current.step_id: current},
        "orchestrator_requests": {
            "fp": {"sent": False, "creation_timestamp": 1.0, "payload": payload}
        },
    }
    command = await orchestrator_request_queue(state, config("t-snapshot"))
    send = command.goto
    check(isinstance(send, Send) and send.node == "orchestrator_node",
          f"unexpected goto: {send!r}")
    sent = send.arg["steps"][current.step_id]
    check(isinstance(sent, Step), f"dispatch sent a {type(sent).__name__}")
    check(sent.preparation_done is True, "stale preparation flag was dispatched")
    check(sent.workdir == "/prepared", f"stale workdir was dispatched: {sent.workdir!r}")


async def test_queue_marks_sent_without_losing_payload() -> None:
    step = make_step("plan-0:step-0:a", status="pending", preparation_done=False)
    payload = {"phase": "preparation", "messages": []}
    state = {
        "finalization": False,
        "steps": {step.step_id: step},
        "orchestrator_requests": {
            "fp": {"sent": False, "creation_timestamp": 1.0, "payload": payload}
        },
    }
    command = await orchestrator_request_queue(state, config("t-sent"))
    merged = orchestrator_request_reducer(
        state["orchestrator_requests"],
        command.update.get("orchestrator_requests") or {},
    )
    check(merged["fp"]["sent"] is True, "the request was not marked sent")
    check(merged["fp"]["payload"] == payload, "the request payload was lost")
    check(merged["fp"]["creation_timestamp"] == 1.0,
          "the creation timestamp was lost")


async def test_running_step_is_not_dispatched_again() -> None:
    with tempfile.TemporaryDirectory() as workdir:
        step = make_step("plan-0:step-0:a", status="pending", workdir=workdir)
        state = preparation_state(step)
        first = await router(state, config("t-running"))
        sends = [item for item in first.goto
                 if isinstance(item, Send) and item.node == "step_node"]
        check(len(sends) == 1, f"expected one StepNode dispatch, got {sends!r}")
        apply_steps(state, first.update.get("steps") or {})
        check(state["steps"][step.step_id].status == "running",
              "the router did not persist status=running")

        second = await router(state, config("t-running"))
        sends = [item for item in second.goto
                 if isinstance(item, Send) and item.node == "step_node"]
        check(sends == [], f"a running step was dispatched twice: {sends!r}")


async def test_step_dispatch_carries_context_and_skill_artifacts() -> None:
    """A skill loaded in this turn must reach the StepNode it enables."""
    with tempfile.TemporaryDirectory() as workdir:
        step = make_step("plan-0:step-0:a", workdir=workdir)
        loaded_skills = {
            "demo": {
                "name": "demo",
                "path": "/skills/demo/skill.md",
                "summary": "demo skill",
                "references": [],
                "scripts": [
                    {"path": "/skills/demo/scripts/run.py", "purpose": "run"}
                ],
            }
        }
        state = {
            "finalization": False,
            "steps": {step.step_id: step},
            "step_results": {},
            "orchestrator_requests": {},
            "loaded_skills": loaded_skills,
            # Deliberately stale/empty: the router must recompute it.
            "skill_artifacts_pathes": set(),
            "project_workdir": "/project",
        }
        command = await router(state, config("t-router"))
        sends = [item for item in command.goto
                 if isinstance(item, Send) and item.node == "step_node"]
        check(len(sends) == 1, f"expected one step dispatch, got {sends!r}")
        arg = sends[0].arg
        check(arg["project_workdir"] == "/project",
              f"the StepNode dispatch lost its project workdir: {arg!r}")
        check("/skills/demo/scripts/run.py" in arg["skill_artifacts_pathes"],
              f"a newly loaded skill script was not allowed: {arg!r}")


async def main() -> None:
    tests = [
        ("delta is empty when unchanged", test_delta_is_empty_when_nothing_changed),
        ("delta contains only changed fields", test_delta_contains_only_changed_fields),
        ("delta preserves concurrent outer changes", test_delta_does_not_clobber_concurrent_outer_changes),
        ("delta keeps new steps as objects", test_delta_keeps_new_steps_as_objects),
        ("fingerprint ignores message ids", test_fingerprint_ignores_message_ids),
        ("identical request keeps one entry", test_identical_request_keeps_one_entry_and_stays_sent),
        ("queue does not redispatch sent request", test_queue_does_not_redispatch_a_sent_request),
        ("queue dispatch uses current snapshot", test_queue_dispatch_uses_current_step_snapshot),
        ("queue keeps payload when marking sent", test_queue_marks_sent_without_losing_payload),
        ("running step is not dispatched twice", test_running_step_is_not_dispatched_again),
        ("step dispatch carries context", test_step_dispatch_carries_context_and_skill_artifacts),
    ]
    for name, function in tests:
        if asyncio.iscoroutinefunction(function):
            await function()
        else:
            function()
        print(f"  ok: {name}")
    print("\nAGENT STATE SYNC TESTS: OK")


if __name__ == "__main__":
    asyncio.run(main())
