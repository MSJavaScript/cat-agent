"""Argument parsers for ``python -m catagent.app`` and the ``catagent`` command.

The definitions live in this small module so the installed console script can
share them without duplicating option names or defaults.
"""

from __future__ import annotations

import argparse
import importlib.metadata

from ._paths import SKILLS_ENV, default_skill_index

__all__ = [
    "_build_command_parser",
    "_build_parser",
    "resolve_common_args",
]


def _version() -> str:
    try:
        return importlib.metadata.version("cat-agent")
    except importlib.metadata.PackageNotFoundError:
        return "0.0.1"


def _add_common_args(parser: argparse.ArgumentParser) -> None:
    parser.add_argument(
        "--dotenv", default=".env", help="Path to the dotenv file."
    )
    parser.add_argument(
        "--db",
        default="catagent_checkpoints.db",
        help="Path to the sqlite checkpoint database.",
    )
    parser.add_argument(
        "--job-manager-url",
        default="http://127.0.0.1:8000",
        help="Base URL of jobmanager.",
    )
    parser.add_argument(
        "--skill-index-json",
        "--skill_index_json",
        dest="skill_index_json",
        default=None,
        help="Path to the skill index JSON file. Default: the skills/ directory "
        f"shipped with cat-agent (override with {SKILLS_ENV}).",
    )
    parser.add_argument(
        "--log",
        default=None,
        help="Path to the catagent log file (default: log to stderr).",
    )
    parser.add_argument(
        "--agent-log-level",
        default="info",
        choices=["debug", "info", "warning", "error", "critical"],
        help="Log level for the catagent logger (default: info).",
    )


def _add_cli_args(parser: argparse.ArgumentParser) -> None:
    parser.add_argument(
        "--thread-id",
        default=None,
        help="Thread id to use. A new one is generated by default.",
    )


def _add_server_args(parser: argparse.ArgumentParser) -> None:
    parser.add_argument(
        "--host",
        default="127.0.0.1",
        help="Bind host (default: 127.0.0.1).",
    )
    parser.add_argument(
        "--port",
        type=int,
        default=5600,
        help="Bind port (default: 5600).",
    )
    parser.add_argument(
        "--url",
        "--catagent-url",
        dest="url",
        default=None,
        help="Bind URL, e.g. http://127.0.0.1:5600. Overrides --host/--port.",
    )
    parser.add_argument(
        "--log-level",
        default="info",
        help="uvicorn log level (default: info).",
    )


def _build_parser(prog: str = "python -m catagent.app") -> argparse.ArgumentParser:
    """Legacy flat parser used by ``python -m catagent.app``."""
    parser = argparse.ArgumentParser(
        prog=prog,
        description="cat-agent debug CLI or HTTP service.",
    )
    _add_common_args(parser)
    _add_cli_args(parser)
    _add_server_args(parser)
    parser.add_argument(
        "--serve",
        action="store_true",
        help="Run the catagent HTTP API instead of the debug CLI.",
    )
    return parser


def _build_command_parser(prog: str = "catagent") -> argparse.ArgumentParser:
    """The installed ``catagent cli`` / ``catagent server`` command."""
    parser = argparse.ArgumentParser(
        prog=prog,
        description="cat-agent: computational catalysis agent.",
    )
    parser.add_argument(
        "--version",
        action="version",
        version=f"cat-agent {_version()}",
    )
    subparsers = parser.add_subparsers(
        dest="command",
        required=True,
        metavar="{cli,server}",
    )

    cli = subparsers.add_parser(
        "cli",
        help="Run the interactive terminal agent (in-process graph).",
        description="Run the interactive terminal agent (in-process graph).",
    )
    _add_common_args(cli)
    _add_cli_args(cli)

    server = subparsers.add_parser(
        "server",
        help="Run the HTTP API and the debug web UI.",
        description="Run the HTTP API and the debug web UI.",
    )
    _add_common_args(server)
    _add_server_args(server)

    return parser


def resolve_common_args(args: argparse.Namespace) -> None:
    """Fill in defaults that need filesystem lookups (the skill index)."""
    if not getattr(args, "skill_index_json", None):
        args.skill_index_json = str(default_skill_index())
