from typing import List
from pydantic import BaseModel, Field
from typing import Callable

class InvalidParameter(Exception):
    '''
    Invalid parameter exception.
    '''
    pass 

class InvalidFileFormat(Exception):
    '''
    Invalid file format exception.
    '''
    pass 

class ToolOutput(BaseModel):
    content: str = Field(description="The output message of tool call. ")
    outfile_list: List[str] =  Field(description="The absolute pathes of files generated by this tool.", default_factory=list)

