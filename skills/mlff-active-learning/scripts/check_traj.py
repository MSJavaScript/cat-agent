"""
If the number of ionic steps in the trajectory larger than the given threshold, structures are randomly extracted from the trajectory.

Usage:
# Extract structures from structures relaxation
python3 check_traj.py --traj opt.traj -o extracted_opt.extxyz -n 5 

# Extract structures from NEB trajectory. Two end points are ignored, 
# because they are IS and FS, which keep fixed during the relaxation.
python3 check_traj.py --traj opt.traj -o extracted_neb.extxyz --neb -n 5 
"""

import argparse
from ase.io import read, write 
import numpy as np 
from random import sample 

def get_structures_distance(atoms1, atoms2)->float:
    if len(atoms1)!= len(atoms2):
        return np.nan
    cell1 = atoms1.get_cell()
    cell2 = atoms2.get_cell()
    if not np.all(np.isclose(cell1, cell2)):
        return np.nan
    frac1 = atoms1.get_scaled_positions()
    frac2 = atoms2.get_scaled_positions()
    diff_frac = frac1 - frac2
    diff_frac[diff_frac > 0.5] -= 1.0
    diff_frac[diff_frac < -0.5] += 1.0
    diff_cart = np.matmul(diff_frac, cell1)
    return np.sum(diff_cart**2.0) ** 0.5 

parser = argparse.ArgumentParser(description="Check the trajectory and extract structures if the trajectory is oscillating.")

parser.add_argument("--traj", 
                    type=str, 
                    required=True, 
                    help="Path to a *.traj file.")

parser.add_argument("-o", "--outfile",
                    type=str,
                    required=True,
                    help="The name of extxyz file to save the extracted structures.")

parser.add_argument("--neb", 
                    action="store_true", 
                    help="If this *.traj file is generated by an NEB job.")

parser.add_argument("--nstep_thres",
                    type=int,
                    default=100,
                    help="If the number of steps in the trajectory larger than this value, consider this trajectory as problematic, structures will be extracted from it. ")

parser.add_argument("-n", 
                    "--n_extract", 
                    type=int, 
                    default=3, 
                    help="Extract how many structures from the trajectory. For NEB, extract from the trajectory of every intermediate image, two end points (IS and FS) are ignored.")

args = parser.parse_args()
traj      = args.traj
outfile = args.outfile
neb       = args.neb
n_extract = args.n_extract
nstep_thres = args.nstep_thres

trajs = read(traj, index=":")
nstruct = len(trajs)

if neb: #如果是NEB的话检测有几个image
    collect_index = [0]
    i = 1
    while len(collect_index) < 4 and i < nstruct:
        d = get_structures_distance(trajs[0], trajs[i])
        if not np.isnan(d) and d < 1.0e-6:
            collect_index.append(i)
        i += 1
    if len(collect_index) == 4:
        a = collect_index[3] - collect_index[2]
        b = collect_index[2] - collect_index[1]
        c = collect_index[1] - collect_index[0]
        if a != b or b != c:
            print("Error:This traj file of NEB might be broken. Initial state was supposed to be unchanged.")
            exit(0)
    else:
        print("No structures are extracted.")
        exit(0)
    nimage = collect_index[1] - collect_index[0]
    nsteps = int(nstruct / float(nimage))
    if nsteps < nstep_thres:
        print("No structures are extracted.")
        exit(0)
    if nsteps * nimage != nstruct:
        print(f"Error: This traj file of NEB might be broken. The number of structures is {nimage}, but the total numebr of structures {nstruct} cannot be divided by it.")
        exit(0)
    result = []
    for i in range(1, nimage-1):
        sub_traj = trajs[i:nstruct:nimage]
        indices = sample(range(len(sub_traj)), n_extract)
        result.extend([sub_traj[i] for i in indices])
    print(f"{len(result)} structures are extracted and saved to {outfile}.")
    write(f"{outfile}", result, format="extxyz")
    exit(0)
else:
    if nstruct < nstep_thres:
        print("No structures are extracted.")
        exit(0)
    indices = sample(range(nstruct), n_extract)
    result = [trajs[i] for i in indices]
    print(f"{n_extract} structures are extracted and saved to {outfile}.")
    write(f"{outfile}", result, format="extxyz")


        



